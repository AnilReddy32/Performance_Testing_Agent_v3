from pathlib import Path
import sys
import argparse
import json
import asyncio
import uuid
import time
from datetime import datetime, timezone
 
ROOT = Path(__file__).resolve().parent
PROJECT_ROOT = ROOT.parent
 
sys.path.insert(0, str(PROJECT_ROOT))
sys.path.insert(0, str(ROOT))
 
from evaluator import evaluate_case
 
from Performance_Testing_Agent.orchestrator.agent import root_agent
 
from google.adk.runners import Runner
from google.adk.sessions import InMemorySessionService
from google.genai import types
 
def discover_cases(case_id=None, category=None):
    """
    Discover all benchmark test cases.
 
    Cases are sorted numerically:
    TC001, TC002, TC003 ... TC100
    """
 
    files = list((ROOT / "test_cases").rglob("TC*.json"))
 
    files = sorted(
        files,
        key=lambda p: int(p.stem.replace("TC", ""))
    )
 
    selected = []
 
    for path in files:
 
        case = json.loads(
            path.read_text(encoding="utf-8")
        )
 
        if case_id and case["id"] != case_id:
            continue
 
        if category and case["category"] != category:
            continue
 
        selected.append(case)
 
    return selected
 
 
def build_prompt(case):
    """
    Build the input prompt for the ADK agent.
 
    Only the user query is sent to the agent.
    Expected agent/tool/flow information is kept
    hidden and is used only by the evaluator.
    """
 
    return case["user_query"]
 
 
def execute_agent(prompt, config):

    """

    Execute the existing Google ADK application directly.
 
    The benchmark sends only the user's query to the ADK root agent.

    """
 
    async def _run():

        session_service = InMemorySessionService()
 
        user_id = "benchmark_user"

        session_id = f"benchmark_{uuid.uuid4().hex}"

        # Matches the app_name convention already used by the project's
        # own Orchestrator class (orchestrator/orchestrator.py) for
        # standalone Runner usage outside adk web - this is just a
        # namespace key for session storage, unrelated to adk web's own
        # auto-discovered "Performance_Testing_Agent.orchestrator" name.
        app_name = "performance_testing_agent"
 
        # Create a fresh session for each benchmark attempt.

        await session_service.create_session(

            app_name=app_name,

            user_id=user_id,

            session_id=session_id,

        )
 
        runner = Runner(

            agent=root_agent,

            app_name=app_name,

            session_service=session_service,

        )
 
        message = types.Content(

            role="user",

            parts=[

                types.Part(

                    text=prompt

                )

            ],

        )
 
        output_parts = []
 
        async for event in runner.run_async(

            user_id=user_id,

            session_id=session_id,

            new_message=message,

        ):

            # Capture text generated by the agent.

            if event.content and event.content.parts:

                for part in event.content.parts:

                    if part.text:

                        output_parts.append(part.text)
 
        return "\n".join(output_parts).strip()
 
    print("\nExecuting ADK agent:")

    print(prompt)
 
    start_time = time.perf_counter()
 
    timeout_seconds = int(config.get("timeout_seconds", 300))

    try:

        output = asyncio.run(
            asyncio.wait_for(_run(), timeout=timeout_seconds)
        )
 
        duration = time.perf_counter() - start_time
 
        # DEBUG: show actual ADK response

        print("\nADK RESPONSE:")

        print(output)

        print("=" * 70)
 
        return {

            "return_code": 0,

            "output": output,

            "duration_seconds": round(

                duration,

                3

            ),

        }
 
    except asyncio.TimeoutError:

        duration = time.perf_counter() - start_time

        print(f"\nADK EXECUTION TIMEOUT after {timeout_seconds}s")

        print("=" * 70)

        return {

            "return_code": -1,

            "output": "",

            "duration_seconds": round(duration, 3),

            "error": f"Timed out after {timeout_seconds} seconds",

        }
 
    except Exception as exc:
 
        duration = time.perf_counter() - start_time
 
        print("\nADK EXECUTION ERROR:")

        print(str(exc))

        print("=" * 70)
 
        return {

            "return_code": -1,

            "output": "",

            "duration_seconds": round(

                duration,

                3

            ),

            "error": str(exc),

        }
 
 
def run_case(case, config):
 
    iterations = int(
        config.get(
            "iterations",
            3
        )
    )
 
    retry_failed = int(
        config.get(
            "retry_failed",
            2
        )
    )
 
    prompt = build_prompt(case)
 
    attempts = []
 
    print(
        f"\n{'=' * 70}"
    )
 
    print(
        f"Running {case['id']}: {case['scenario']}"
    )
 
    print(
        f"Category: {case['category']}"
    )
 
    print(
        f"{'=' * 70}"
    )
 
    # --------------------------------------------------
    # Normal iterations
    # --------------------------------------------------
 
    for iteration in range(
        1,
        iterations + 1
    ):
 
        print(
            f"\nIteration {iteration}/{iterations}"
        )
 
        try:
 
            execution = execute_agent(
                prompt,
                config
            )
 
            evaluation = evaluate_case(
                case,
                execution["output"]
            )
 
            attempts.append(
                {
                    "attempt": iteration,
                    "attempt_type": "iteration",
                    "iteration": iteration,
                    "retry": 0,
                    "execution": execution,
                    "evaluation": evaluation
                }
            )
 
            print(
                f"Result: "
                f"{'PASS' if evaluation['passed'] else 'FAIL'}"
            )
 
        except Exception as exc:
 
            attempts.append(
                {
                    "attempt": iteration,
                    "attempt_type": "iteration",
                    "iteration": iteration,
                    "retry": 0,
                    "execution": {
                        "return_code": -1,
                        "output": "",
                        "duration_seconds": 0,
                        "error": str(exc)
                    },
                    "evaluation": {
                        "passed": False,
                        "score": 0,
                        "checks": {
                            "runner_error": False
                        }
                    }
                }
            )
 
            print(
                f"Execution error: {exc}"
            )
 
    # --------------------------------------------------
    # Retry failed case
    # --------------------------------------------------
 
    case_passed = any(
        attempt["evaluation"].get(
            "passed",
            False
        )
        for attempt in attempts
    )
 
    if not case_passed:
 
        print(
            f"\nCase failed after "
            f"{iterations} iterations."
        )
 
        print(
            f"Starting {retry_failed} retry attempt(s)..."
        )
 
        for retry in range(
            1,
            retry_failed + 1
        ):
 
            print(
                f"\nRetry {retry}/{retry_failed}"
            )
 
            try:
 
                execution = execute_agent(
                    prompt,
                    config
                )
 
                evaluation = evaluate_case(
                    case,
                    execution["output"]
                )
 
                attempts.append(
                    {
                        "attempt": len(attempts) + 1,
                        "attempt_type": "retry",
                        "iteration": iterations,
                        "retry": retry,
                        "execution": execution,
                        "evaluation": evaluation
                    }
                )
 
                print(
                    f"Retry result: "
                    f"{'PASS' if evaluation['passed'] else 'FAIL'}"
                )
 
                if evaluation["passed"]:
                    case_passed = True
                    break
 
            except Exception as exc:
 
                attempts.append(
                    {
                        "attempt": len(attempts) + 1,
                        "attempt_type": "retry",
                        "iteration": iterations,
                        "retry": retry,
                        "execution": {
                            "return_code": -1,
                            "output": "",
                            "duration_seconds": 0,
                            "error": str(exc)
                        },
                        "evaluation": {
                            "passed": False,
                            "score": 0,
                            "checks": {
                                "runner_error": False
                            }
                        }
                    }
                )
 
    # --------------------------------------------------
    # Final result
    # --------------------------------------------------
 
    final_attempt = attempts[-1]
 
    return {
        "id": case["id"],
        "category": case["category"],
        "scenario": case["scenario"],
        "user_query": case["user_query"],
        "expected_agent": case.get("evaluation", {}).get("required_agent", ""),
        "expected_tool": case.get("evaluation", {}).get("required_tool", ""),
        "iterations_requested": iterations,
        "retries_requested": retry_failed,
        "total_attempts": len(attempts),
        "pass_at_k": case_passed,
        "final_status": (
            "PASS"
            if case_passed
            else "FAIL"
        ),
        "final_score": final_attempt[
            "evaluation"
        ].get(
            "score",
            0
        ),
        "attempts": attempts
    }
 
 
def summarize(results):
 
    executed = [
        result
        for result in results
        if result["final_status"]
        in [
            "PASS",
            "FAIL"
        ]
    ]
 
    passed = [
        result
        for result in executed
        if result["final_status"] == "PASS"
    ]
 
    failed = [
        result
        for result in executed
        if result["final_status"] == "FAIL"
    ]
 
    total_attempts = sum(
        result.get(
            "total_attempts",
            0
        )
        for result in executed
    )
 
    pass_at_k = sum(
        bool(
            result.get(
                "pass_at_k",
                False
            )
        )
        for result in executed
    )
 
    return {
        "cases": len(results),
        "executed": len(executed),
        "passed": len(passed),
        "failed": len(failed),
        "total_attempts": total_attempts,
        "pass_rate": round(
            (
                len(passed)
                / len(executed)
                * 100
            )
            if executed
            else 0,
            2
        ),
        "pass_at_k": round(
            (
                pass_at_k
                / len(executed)
                * 100
            )
            if executed
            else 0,
            2
        )
    }
 
 
def main():
 
    parser = argparse.ArgumentParser(
        description=(
            "ANZ Banking AI "
            "Performance Testing Benchmark"
        )
    )
 
    parser.add_argument(
        "--case",
        help="Run a specific test case, e.g. TC066"
    )
 
    parser.add_argument(
        "--category",
        help=(
            "Run a category, e.g. "
            "analysis"
        )
    )
 
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Discover cases without executing agents"
    )

    parser.add_argument(
        "--output",
        help="Output file name (default: benchmark_results.json)"
    )
 
    args = parser.parse_args()
 
    # --------------------------------------------------
    # Load configuration
    # --------------------------------------------------
 
    config_path = (
        ROOT
        / "benchmark_config.json"
    )
 
    config = json.loads(
        config_path.read_text(
            encoding="utf-8"
        )
    )
 
    # --------------------------------------------------
    # Discover test cases
    # --------------------------------------------------
 
    cases = discover_cases(
        case_id=args.case,
        category=args.category
    )
 
    if not cases:
 
        print(
            "No benchmark test cases found."
        )
 
        return
 
    print(
        f"\nFound {len(cases)} benchmark cases."
    )
 
    # --------------------------------------------------
    # Execute
    # --------------------------------------------------
 
    results = []
 
    for index, case in enumerate(
        cases,
        start=1
    ):
 
        print(
            f"\n[{index}/{len(cases)}] "
            f"{case['id']} "
            f"{case['scenario']}"
        )
 
        if args.dry_run:
 
            results.append(
                {
                    "id": case["id"],
                    "category": case["category"],
                    "scenario": case["scenario"],
                    "final_status": "NOT_RUN"
                }
            )
 
        else:
 
            result = run_case(
                case,
                config
            )
 
            results.append(
                result
            )
 
    # --------------------------------------------------
    # Build benchmark result
    # --------------------------------------------------
 
    benchmark_result = {
 
        "benchmark": (
            "ANZ Banking AI "
            "Performance Testing Benchmark"
        ),
 
        "generated_at": (
            datetime.now(
                timezone.utc
            ).isoformat()
        ),
 
        "input_type": "user_query",
 
        "cases": results,
 
        "summary": summarize(
            results
        )
    }
 
    # --------------------------------------------------
    # Save results
    # --------------------------------------------------
 
    output_path = (
        ROOT
        / (args.output or "benchmark_results.json")
    )
 
    output_path.write_text(
        json.dumps(
            benchmark_result,
            indent=2
        ),
        encoding="utf-8"
    )
 
    # --------------------------------------------------
    # Print summary
    # --------------------------------------------------
 
    print(
        "\n"
        + "=" * 70
    )
 
    print(
        "BENCHMARK SUMMARY"
    )
 
    print(
        "=" * 70
    )
 
    print(
        json.dumps(
            benchmark_result["summary"],
            indent=2
        )
    )
 
    print(
        "\nResults saved to:"
    )
 
    print(
        output_path
    )
 
 
if __name__ == "__main__":
    main()